import React, { useEffect, useState } from 'react';

const API = import.meta.env.VITE_API_URL;

function Insights() {
  const [tips, setTips] = useState([
    {
      tag: 'Subscription Overlap',
      title: 'You have recurring services worth reviewing',
      desc: 'Consolidating duplicate subscriptions could improve monthly cash flow.',
      icon: 'stars',
      theme: 'primary',
      card: 'bg-surface-container-highest',
    },
    {
      tag: 'Savings Opportunity',
      title: 'A small surplus can be redirected to savings',
      desc: 'Move this month’s extra balance into an emergency or investment fund.',
      icon: 'trending_up',
      theme: 'secondary',
      card: 'bg-surface-container-high',
    },
  ]);

  useEffect(() => {
    const loadInsights = async () => {
      try {
        const res = await fetch(`${API}/api/suggest?user_id=demo_user`);
        const json = await res.json();

        const raw =
          json?.suggestions ||
          '';

        const lines = String(raw)
          .split('\n')
          .map((line) => line.replace(/^\d+\.\s*/, '').trim())
          .filter(Boolean);

        const first = lines[0] || 'You are maintaining a good start toward financial discipline.';
        const second =
          lines[1] ||
          'Set category-wise limits and monitor weekly spending for better control.';
        const third =
          lines[2] ||
          'Review recurring expenses regularly to unlock extra savings.';

        setTips([
          {
            tag: 'Subscription Overlap',
            title: first,
            desc: second,
            icon: 'stars',
            theme: 'primary',
            card: 'bg-surface-container-highest',
          },
          {
            tag: 'Savings Opportunity',
            title: third,
            desc:
              lines[3] ||
              'Use monthly surpluses wisely and stay consistent with savings goals.',
            icon: 'trending_up',
            theme: 'secondary',
            card: 'bg-surface-container-high',
          },
        ]);
      } catch (error) {
        console.error('Insights load failed:', error);
      }
    };

    loadInsights();
  }, []);

  return (
    <main className="relative z-10 pt-24 md:pt-32 pb-32 md:pb-24 px-4 md:px-10 max-w-4xl mx-auto flex flex-col gap-8">
      <div className="flex flex-col gap-2 text-center items-center">
        <h1 className="font-headline-xl text-3xl md:text-5xl font-bold text-on-surface">
          Smart Suggestions
        </h1>
        <p className="font-body-md text-on-surface-variant max-w-lg">
          Actionable, highly contextual alerts generated by your Autonomous Financial Twin.
        </p>
      </div>

      <div className="flex flex-col gap-4 mt-8">
        {tips.map((tip, index) => (
          <div
            key={index}
            className={`p-6 ${tip.card} border-l-2 border-${tip.theme} rounded-r-sm flex flex-col gap-2`}
          >
            <div className="flex items-center gap-2">
              <span
                className={`material-symbols-outlined text-${tip.theme} text-sm`}
              >
                {tip.icon}
              </span>
              <span
                className={`font-label-lg text-${tip.theme} text-xs uppercase tracking-widest`}
              >
                {tip.tag}
              </span>
            </div>

            <h3 className="font-headline-md text-xl text-on-surface">
              {tip.title}
            </h3>

            <p className="font-body-sm text-on-surface-variant">
              {tip.desc}
            </p>
          </div>
        ))}
      </div>
    </main>
  );
}

export default Insights;
